    /**
     Проверяет, поддерживается ли эмодзи на текущем устройстве.
     На Android hasGlyph() некорректно работает с emoji sequences и флагами,
     поэтому показываем все эмодзи без фильтрации.
     @param emoji Строка с эмодзи
     @return true если эмодзи не пустой
     */
    public static boolean isEmojiSupported(@NonNull String emoji) {
        // Пустые строки - это заглушки для визуальных пропусков в сетке
        return !emoji.isEmpty();

        // Показываем все эмодзи без фильтрации
        // Paint.hasGlyph() может возвращать false для валидных эмодзи:
        // - Emoji sequences (‍👩‍👧, 🏳️‍🌈)
        // - Флаги стран (🇷, 🇺🇸)
        // - Эмодзи с вариационными селекторами (☺️)
    }

    /**
     Возвращает список эмодзи для категории.
     Фильтрация через hasGlyph() отключена из-за некорректной работы на Android.
     @param category Код категории
     @return Список эмодзи (без пустых строк)
     */
    @NonNull
    public static List<String> getEmojisForCategory(@NonNull String category) {
        List<String> allEmojis = getRawEmojisForCategory(category);
        List<String> result = new ArrayList<>(allEmojis.size());
        for (String emoji : allEmojis) {
            if (isEmojiSupported(emoji)) {
                result.add(emoji);
            }
        }
        return result;
    }

    /**
     * Находит индекс категории, в которой находится указанный эмодзи.
     * Возвращает 0 (первая категория), если эмодзи не найден.
     * @param emoji Эмодзи для поиска
     * @return Индекс категории
     */
    public static int findCategoryIndexForEmoji(String emoji) {
        if (emoji == null || emoji.isEmpty()) return 0;
        List<String> allCategories = getAllCategories();
        for (int i = 0; i < allCategories.size(); i++) {
            List<String> emojis = getEmojisForCategory(allCategories.get(i));
            if (emojis.contains(emoji)) {
                return i;
            }
        }
        return 0;
    }

